import { promises as fs } from "node:fs";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { v2 as cloudinary } from "cloudinary";
import sharp from "sharp";

const currentDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(currentDirectory, "..");
const imageRoot = path.join(projectRoot, "public", "images");
const generatedAssetFile = path.join(projectRoot, "src", "lib", "cloudinary-assets.ts");
const supportedExtensions = new Set([".png", ".jpg", ".jpeg", ".heic", ".webp", ".avif"]);
const passthroughExtensions = new Set([".webp", ".avif"]);
const execFileAsync = promisify(execFile);

if (!process.env.CLOUDINARY_URL) {
  throw new Error(
    "Missing CLOUDINARY_URL. Add it to .env.local or run CLOUDINARY_URL=cloudinary://<api_key>:<api_secret>@<cloud_name> pnpm upload:images.",
  );
}

cloudinary.config({ secure: true });

async function getFiles(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const fullPath = path.join(directory, entry.name);
      return entry.isDirectory() ? getFiles(fullPath) : [fullPath];
    }),
  );
  return files.flat();
}

function getFolder(relativePath) {
  const sourceFolder = path.dirname(relativePath);
  const section = sourceFolder === "." ? "core" : sourceFolder.replaceAll(path.sep, "/");
  return `chicas-sc/${section}`;
}

function uploadBuffer(buffer, options) {
  return new Promise((resolve, reject) => {
    const stream = cloudinary.uploader.upload_stream(options, (error, result) => {
      if (error) reject(error);
      else resolve(result);
    });
    stream.end(buffer);
  });
}

function toDeliveryUrl(publicId) {
  return `https://res.cloudinary.com/${cloudinary.config().cloud_name}/image/upload/f_auto,q_auto/${publicId}`;
}

function generatedModule(assets) {
  return `/** Generated by scripts/upload-images-to-cloudinary.mjs. Do not edit manually. */\n` +
    `export const cloudinaryAssets: Record<string, string> = ${JSON.stringify(assets, null, 2)};\n\n` +
    `export function cloudinaryAsset(localPath: string) {\n` +
    `  return cloudinaryAssets[localPath] ?? localPath;\n` +
    `}\n`;
}

async function convertToWebp(file, extension) {
  try {
    return await sharp(file).rotate().webp({ quality: 82, effort: 5 }).toBuffer();
  } catch (error) {
    // Some HEIC files use HEVC, whose decoder is not bundled with Sharp. macOS
    // ships `sips`, so use it only as a local fallback for those source files.
    if (extension !== ".heic" || process.platform !== "darwin") throw error;

    const temporaryPng = path.join(tmpdir(), `chicas-sc-${Date.now()}-${path.basename(file)}.png`);
    try {
      await execFileAsync("sips", ["-s", "format", "png", file, "--out", temporaryPng]);
      return await sharp(temporaryPng).rotate().webp({ quality: 82, effort: 5 }).toBuffer();
    } finally {
      await fs.rm(temporaryPng, { force: true });
    }
  }
}

const allFiles = await getFiles(imageRoot);
const imageFiles = allFiles.filter((file) => supportedExtensions.has(path.extname(file).toLowerCase()));
const assets = {};

for (const file of imageFiles) {
  const relativePath = path.relative(imageRoot, file);
  const extension = path.extname(file).toLowerCase();
  const localPath = `/images/${relativePath.replaceAll(path.sep, "/")}`;
  const publicId = `chicas-sc/${relativePath
    .slice(0, -path.extname(relativePath).length)
    .replaceAll(path.sep, "/")}`;
  const format = passthroughExtensions.has(extension) ? extension.slice(1) : "webp";
  const input = passthroughExtensions.has(extension)
    ? await fs.readFile(file)
    : await convertToWebp(file, extension);

  const result = await uploadBuffer(input, {
    asset_folder: getFolder(relativePath),
    public_id: publicId,
    overwrite: true,
    invalidate: true,
    resource_type: "image",
    format,
  });

  assets[localPath] = toDeliveryUrl(result.public_id);
  console.log(`${passthroughExtensions.has(extension) ? "Kept" : "Converted"} ${localPath}`);
}

await fs.writeFile(generatedAssetFile, generatedModule(assets));
console.log(`\nUploaded ${imageFiles.length} image(s) and updated src/lib/cloudinary-assets.ts.`);
